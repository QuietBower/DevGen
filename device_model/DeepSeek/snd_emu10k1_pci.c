static uint64_t pcibase_pio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    if (addr == 0x00) {
        /* AC97 Address register: return last written value */
        val = s->ac97_addr;
    } else if (addr == 0x04) {
        if (size == 2) {
            uint8_t reg = s->ac97_addr & 0x7f;
            /* AC97 reset register (0) always reports Codec Ready */
            if (reg == 0) {
                val = 0x8000;
            } else {
                val = s->ac97_regs[reg];
            }
        } else {
            val = 0xFFFFFFFFu;
        }
    } else {
        /* Default for other offsets */
        val = 0xFFFFFFFFu;
    }
    return val;
}

static void pcibase_pio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;

    if (addr == 0x00) {
        s->ac97_addr = (uint16_t)val;
    } else if (addr == 0x04) {
        if (size == 2 || size == 4) {
            s->ac97_regs[(s->ac97_addr & 0x7f)] = (uint16_t)val;
        }
    } else {
        /* Ignore writes to other offsets */
    }
}

