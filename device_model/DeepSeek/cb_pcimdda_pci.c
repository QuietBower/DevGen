static uint64_t pcibase_pio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    if (addr >= 16) {
        return ~0ULL;
    }

    switch (size) {
    case 1:
        val = s->regs[addr];
        break;
    case 2:
        if (addr < 15) {
            val = (uint16_t)(s->regs[addr] | (s->regs[addr + 1] << 8));
        } else {
            val = (uint16_t)s->regs[addr];
        }
        break;
    case 4:
        if (addr < 13) {
            val = (uint32_t)(s->regs[addr] | (s->regs[addr + 1] << 8) |
                             (s->regs[addr + 2] << 16) | (s->regs[addr + 3] << 24));
        } else if (addr == 13) {
            val = (uint32_t)(s->regs[13] | (s->regs[14] << 8) | (s->regs[15] << 16));
        } else if (addr == 14) {
            val = (uint32_t)(s->regs[14] | (s->regs[15] << 8));
        } else {
            val = (uint32_t)s->regs[addr];
        }
        break;
    default:
        val = 0;
        break;
    }

    return val;
}

static void pcibase_pio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;

    if (addr >= 16) {
        return;
    }

    switch (size) {
    case 1:
        s->regs[addr] = (uint8_t)val;
        break;
    case 2:
        if (addr < 15) {
            s->regs[addr] = (uint8_t)(val & 0xff);
            s->regs[addr + 1] = (uint8_t)((val >> 8) & 0xff);
        } else {
            s->regs[addr] = (uint8_t)(val & 0xff);
        }
        break;
    case 4:
        if (addr < 13) {
            s->regs[addr] = (uint8_t)(val & 0xff);
            s->regs[addr + 1] = (uint8_t)((val >> 8) & 0xff);
            s->regs[addr + 2] = (uint8_t)((val >> 16) & 0xff);
            s->regs[addr + 3] = (uint8_t)((val >> 24) & 0xff);
        } else if (addr == 13) {
            s->regs[13] = (uint8_t)(val & 0xff);
            s->regs[14] = (uint8_t)((val >> 8) & 0xff);
            s->regs[15] = (uint8_t)((val >> 16) & 0xff);
        } else if (addr == 14) {
            s->regs[14] = (uint8_t)(val & 0xff);
            s->regs[15] = (uint8_t)((val >> 8) & 0xff);
        } else {
            s->regs[addr] = (uint8_t)(val & 0xff);
        }
        break;
    default:
        break;
    }
}

