static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    switch (addr) {
    case GMD_ID:
        /* return graphics GMDID: raw value that decodes to version 1255 (Xe_HPG) */
        val = 0x00001255;  /* placeholder raw value; needs GMD_ID_ARCH_MASK, etc. */
        break;
    case GMD_ID + MEDIA_GT_GSI_OFFSET:
        /* media GMDID: return 0 to indicate media not present */
        val = 0;
        break;
    case XEHP_MTCFG_ADDR:
        /* return 0, meaning tile_count=1 after extraction */
        val = 0;
        break;
    default:
        val = 0;
        break;
    }

    return val;
}

