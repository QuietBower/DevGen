/* Internal helper for status-triggered signaling. */
static void pcibase_update_irq(PCIBaseState *s)
{
    PCIDevice *pdev = PCI_DEVICE(s);
    uint32_t status = s->h_csr & H_CSR_IS_MASK; /* H_IS | H_D0I3C_IS */
    uint32_t enable = s->h_csr & H_CSR_IE_MASK; /* H_IE | H_D0I3C_IE */
    bool irq_pending = (status & H_IS) && (enable & H_IE);
    irq_pending |= (status & H_D0I3C_IS) && (enable & H_D0I3C_IE);

    if (irq_pending) {
        if (msi_enabled(pdev)) {
            msi_notify(pdev, 0);
        } else {
            pci_set_irq(pdev, 1);
        }
    } else {
        if (!msi_enabled(pdev)) {
            pci_set_irq(pdev, 0);
        }
    }
}

