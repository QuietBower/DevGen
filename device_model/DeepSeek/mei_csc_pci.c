/* MMIO/PIO Handlers generated during Behavioral Modeling */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    switch (addr) {
    case H_CSR:
        val = s->h_csr;
        break;
    case ME_CSR_HA:
        val = s->me_csr_ha;
        break;
    default:
        /* For unhandled regions (including firmware status area), return 0 */
        break;
    }
    return val;
}

static void pcibase_mmio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;
    uint32_t val32 = (uint32_t)val;

    switch (addr) {
    case H_CSR:
        /* Write-1-to-clear for interrupt status bits */
        if (val32 & H_IS) {
            s->h_csr &= ~H_IS;
        }
        if (val32 & H_D0I3C_IS) {
            s->h_csr &= ~H_D0I3C_IS;
        }
        /* Update interrupt enable bits */
        s->h_csr &= ~H_CSR_IE_MASK;
        s->h_csr |= (val32 & H_CSR_IE_MASK);
        /* H_RDY is treated as read-only and ignored on write. */
        /* H_IG is not implemented; writing to it has no effect. */
        pcibase_update_irq(s);
        break;
    case ME_CSR_HA:
        s->me_csr_ha = val32;
        /* ME_RST_HRA bit may initiate hardware reset; left as a simple write for now. */
        break;
    default:
        /* Ignore writes to other addresses */
        break;
    }
}

