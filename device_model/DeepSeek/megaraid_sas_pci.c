static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;
    uint32_t idx = addr >> 2;

    if (addr >= 0x1000 || size != 4) {
        return 0xFFFFFFFF;
    }

    val = s->regs[idx];
    return val;
}

static void pcibase_mmio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;
    uint32_t idx = addr >> 2;

    if (addr >= 0x1000 || size != 4) {
        return;
    }

    switch (addr) {
    case MFI_INBOUND_QUEUE_PORT:
        process_inbound_command(s, val);
        break;
    case MFI_OUTBOUND_INTR_STATUS:
        /* Write-1-to-clear */
        s->regs[idx] &= ~val;
        pcibase_update_irq(s);
        break;
    case MFI_OUTBOUND_INTR_MASK:
        s->regs[idx] = val;
        pcibase_update_irq(s);
        break;
    default:
        s->regs[idx] = val;
        break;
    }
}

