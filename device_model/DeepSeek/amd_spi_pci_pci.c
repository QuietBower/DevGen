/* Register Layout and Hardware Identifiers extracted from driver source */
#define AMD_PCI_DEVICE_ID_LPC_BRIDGE 0x1682
#define DEVICE_VENDOR_ID 0x1022
#define DEVICE_DEVICE_ID AMD_PCI_DEVICE_ID_LPC_BRIDGE
#define DEVICE_CLASS_ID 0xff00
#define AMD_PCI_LPC_SPI_BASE_ADDR_REG 0xA0
#define AMD_SPI_BASE_ADDR_MASK ~0xFF
#define AMD_HID2_PCI_BAR_OFFSET 0x00002000
#define AMD_HID2_MEM_SIZE 0x200

/* Newly provided driver registers */
#define AMD_SPI_HID2_CNTRL          0x150
#define AMD_SPI_HID2_INT_MASK       0x158
#define AMD_SPI_HID2_DMA_SIZE       4096

typedef enum {
    BAR_TYPE_NONE = 0,
    BAR_TYPE_MMIO,
    BAR_TYPE_PIO,
    BAR_TYPE_RAM 
} BARType;

typedef struct {
    int     index;    /* BAR index 0-5 */
    BARType type;
    hwaddr  size;
    const char *name;
} BARInfo;

struct PCIBaseState {
    PCIDevice parent_obj;

    /* Resource Management */
    MemoryRegion bar_regions[6];
    BARInfo bar_info[6];
    int num_bars;

    /* Hardware Register Shadows (The 'Identity' of the device) */
    uint32_t version;

    uint32_t status;

    /* HID2 SPI registers */
    uint32_t hid2_int_mask;
    uint32_t hid2_ctrl;
};

enum amd_spi_versions {
    AMD_SPI_V1 = 1,
    AMD_SPI_V2,
    AMD_HID2_SPI,
};

/* Custom PCI config read to expose BAR0 base at 0xA0 */
static uint32_t pcibase_config_read(PCIDevice *pdev, uint32_t addr, int len)
{
    if (addr == AMD_PCI_LPC_SPI_BASE_ADDR_REG && len == 4) {
        return pci_default_read_config(pdev, PCI_BASE_ADDRESS_0, 4);
    }
    return pci_default_read_config(pdev, addr, len);
}

/* MMIO/PIO Handlers generated during Behavioral Modeling */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    switch (addr) {
    case AMD_SPI_HID2_CNTRL:
        val = s->hid2_ctrl;
        break;
    case AMD_SPI_HID2_INT_MASK:
        val = s->hid2_int_mask;
        break;
    default:
        break;
    } 
    return val;
}

