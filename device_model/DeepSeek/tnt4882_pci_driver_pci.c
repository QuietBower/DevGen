/* MMIO/PIO Handlers - minimal implementation for probe (all reads return 0) */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;
    switch (addr) {
        case MITE_IODWBSR:
            val = s->mite_iodwbsr;
            break;
        default:
            break;
    }
    return val;
}

static void pcibase_mmio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;
    switch (addr) {
        case MITE_IODWBSR:
            s->mite_iodwbsr = val;
            break;
        default:
            break;
    }
}

