/* MMIO/PIO Handlers generated during Behavioral Modeling */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    if (addr >= sizeof(s->regs)) {
        return 0;
    }

    switch (addr) {
    case TG3PCI_MISC_HOST_CTRL:
        val = 0x00000000; /* return chiprev etc. handled above */
        break;
    case VCPU_STATUS:
        val = VCPU_STATUS_INIT_DONE; /* firmware ready */
        break;
    case GRC_MISC_CFG:
        val = 0; /* default */
        break;
    case MEMARB_MODE:
        val = MEMARB_MODE_ENABLE;
        break;
    default:
        val = s->regs[addr / 4];
        break;
    }
    return val;
}

static void pcibase_mmio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;

    if (addr >= sizeof(s->regs)) {
        return;
    }

    s->regs[addr / 4] = val;

    /* handle side-effects: e.g., register indirect access */
    switch (addr) {
    case TG3PCI_REG_BASE_ADDR:
        /* indirect address set */
        break;
    case TG3PCI_REG_DATA:
        /* indirect data write (not used in probe) */
        break;
    case TG3PCI_MEM_WIN_BASE_ADDR:
        /* SRAM access base address */
        break;
    case TG3PCI_MEM_WIN_DATA:
        /* SRAM data write via MEM_WIN: handle writes to SRAM areas like firmware mailbox */
        {
            uint32_t sram_addr = s->regs[TG3PCI_MEM_WIN_BASE_ADDR / 4];
            if (sram_addr < sizeof(s->sram)) {
                memcpy(&s->sram[sram_addr], &val, sizeof(val));
            }
        }
        break;
    case TG3PCI_MISC_HOST_CTRL:
        /* need to update shadow reg */
        break;
    }
}

static uint64_t pcibase_pio_read(void *opaque, hwaddr addr, unsigned size)
{
    /* PIO not used */
    return 0;
}

static void pcibase_pio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    /* PIO not used */
}

