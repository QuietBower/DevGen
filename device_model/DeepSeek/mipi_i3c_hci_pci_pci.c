static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    switch (addr) {
    case 0x04:   /* HC_CONTROL for instance 0 */
    case 0x404:  /* HC_CONTROL for instance 1 */
        val = HC_CONTROL_BUS_ENABLE;
        break;
    case 0x2b4:  /* INTEL_RESETS */
        val = INTEL_RESETS_RESET_DONE;
        break;
    case 0x2bc:  /* INTEL_ACTIVELTR */
        val = s->active_ltr;
        break;
    case 0x2c0:  /* INTEL_IDLELTR */
        val = s->idle_ltr;
        break;
    default:
        val = 0;
        break;
    }
    return val;
}

