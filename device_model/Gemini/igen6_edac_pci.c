/* Register Layout and Hardware Identifiers extracted from driver source */
#define DID_EHL_SKU5 0x4514
#define MCHBAR_OFFSET 0x48
#define MCHBAR_SIZE 0x10000
#define TOM_OFFSET 0xa0
#define TOUUD_OFFSET 0xa8
#define TOLUD_OFFSET 0xbc
#define ERRSTS_OFFSET 0xc8
#define ERRCMD_OFFSET 0xca
#define CAPID_C_OFFSET 0xec
#define CAPID_E_OFFSET 0xf0

#define MCHBAR_EN			BIT_ULL(0)
#define CAPID_C_IBECC			BIT(15)
#define CAPID_E_IBECC			BIT(12)
#define CAPID_E_IBECC_BIT18		BIT(18)
#define ERRSTS_CE			BIT_ULL(6)
#define ERRSTS_UE			BIT_ULL(7)
#define ERRCMD_CE			BIT_ULL(6)

#define ECC_ERROR_LOG_CE		BIT_ULL(62)
#define ECC_ERROR_LOG_UE		BIT_ULL(63)
#define IBECC_ACTIVATE_EN		BIT(0)

#define NUM_CHANNELS			2
#define NUM_DIMMS			2
#define NUM_IMC				2

typedef enum {
    BAR_TYPE_NONE = 0,
    BAR_TYPE_MMIO,
    BAR_TYPE_PIO,
    BAR_TYPE_RAM 
} BARType;

typedef struct {
    int     index;    /* BAR index 0-5 */
    BARType type;
    hwaddr  size;
    const char *name;
} BARInfo;

struct PCIBaseState {
    PCIDevice parent_obj;

    /* Resource Management */
    MemoryRegion bar_regions[6];
    BARInfo bar_info[6];
    int num_bars;

    /* Capability and Interrupt State */
    bool has_msi;
    bool has_msix;
    
    /* Hardware Register Shadows (The 'Identity' of the device) */
    uint64_t mchbar;
    uint64_t tom;
    uint64_t touud;
    uint32_t tolud;
    uint16_t errsts;
    uint16_t errcmd;
    uint32_t capid_c;
    uint32_t capid_e;
};

/* MMIO/PIO Handlers generated during Behavioral Modeling */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    switch (addr) {
    case 0x13c00: /* MCHBAR_MEMSS_IBECCDIS */
        val = 0; /* Bit 6 = 0 (IBECC enabled) */
        break;
    default:
        /* Unimplemented registers will return 0 */
        break;
    }
    
    return val;
}

