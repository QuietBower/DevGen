/* MMIO/PIO Handlers generated during Behavioral Modeling */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    /* The driver uses readl() which is 32-bit little-endian, so enforce 4-byte accesses
     * for the registers we model.
     */

    switch (addr) {
    case INTEL_ACTIVELTR:
        val = s->regs.active_ltr;
        break;
    case INTEL_IDLELTR:
        val = s->regs.idle_ltr;
        break;
    case INTEL_RESETS:
        /* Expose current reset register shadow */
        val = s->regs.resets;
        break;
    default:
        /* For unmapped addresses, return 0 to keep the driver happy */
        val = 0;
        break;
    }

    /* Mask to 32 bits as readl() expects */
    return (uint32_t)val;
}

static void pcibase_mmio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;
    uint32_t v = (uint32_t)val;

    /* The driver uses writel(), i.e. 32-bit little-endian accesses. */

    switch (addr) {
    case INTEL_ACTIVELTR:
        /* The LTR logic in the driver updates both ACTIVE and IDLE and then
         * caches them via intel_cache_ltr(). We simply reflect what is written.
         */
        s->regs.active_ltr = v;
        break;
    case INTEL_IDLELTR:
        s->regs.idle_ltr = v;
        break;
    case INTEL_RESETS:
        /* intel_reset() in the driver does:
         *   writel(0, priv + INTEL_RESETS);
         *   readl_poll_timeout(priv + INTEL_RESETS, reg,
         *                      reg & INTEL_RESETS_RESET_DONE, ...);
         *   writel(INTEL_RESETS_RESET, priv + INTEL_RESETS);
         *
         * We emulate this by:
         *  - when 0 is written: clear RESET bit and set RESET_DONE to indicate
         *    that reset completed
         *  - when INTEL_RESETS_RESET is written: set RESET and clear RESET_DONE
         */
        if (v == 0) {
            s->regs.resets &= ~INTEL_RESETS_RESET;
            s->regs.resets |= INTEL_RESETS_RESET_DONE;
        } else if (v & INTEL_RESETS_RESET) {
            s->regs.resets |= INTEL_RESETS_RESET;
            s->regs.resets &= ~INTEL_RESETS_RESET_DONE;
        } else {
            /* For any other value, just store it */
            s->regs.resets = v;
        }
        break;
    default:
        /* Ignore writes to other offsets */
        break;
    }
}

