/*
 * QEMU PCI device model skeleton for linux-6.18/drivers/usb/host/ehci-pci.c
 *
 * This model only exposes enough PCI identity to let the ehci-pci driver
 * bind and then let the generic EHCI core (ehci-hcd) take over using
 * QEMU's existing EHCI implementation if wired, or simply satisfy probe
 * expectations at the PCI level. The provided driver source does not show
 * any direct MMIO/PIO register accesses here, so BARs and runtime logic
 * are kept minimal.
 */

