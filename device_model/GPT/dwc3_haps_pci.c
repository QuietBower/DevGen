/*
 * DWC3 HAPS PCI QEMU Device Model
 *
 * Functional behavior derived strictly from linux-6.18/drivers/usb/dwc3/dwc3-haps.c
 *
 * NOTE:
 * - The dwc3-haps PCI driver only enables the device, sets it as bus master,
 *   and passes BAR0 + IRQ to a child platform device. It does not touch
 *   any device-specific registers in this driver.
 * - Therefore, this model provides a minimal PCI endpoint with a single
 *   MMIO BAR and a legacy INTx interrupt line. No device-specific MMIO,
 *   DMA, or IRQ status logic is required by the provided code.
 */

