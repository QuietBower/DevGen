static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    BAROpaque *bo = (BAROpaque *)opaque;
    uint64_t val = 0;

    if (addr + size > bo->s->bar_info[bo->bar_index].size) {
        return ~0ULL;
    }
    memcpy(&val, &bo->regs[addr], size);
    return val;
}

static void pcibase_mmio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    BAROpaque *bo = (BAROpaque *)opaque;
    if (addr + size > bo->s->bar_info[bo->bar_index].size) {
        return;
    }
    memcpy(&bo->regs[addr], &val, size);
}

