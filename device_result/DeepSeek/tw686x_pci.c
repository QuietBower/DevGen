/* Internal helper for status-triggered signaling */
static void pcibase_update_irq(PCIBaseState *s)
{
    PCIDevice *pdev = PCI_DEVICE(s);

    /* Raise IRQ if any interrupt status bits are set (e.g., INT_STATUS) */
    if (s->regs[INT_STATUS/4] != 0) {
        pci_set_irq(pdev, 1);
    } else {
        pci_set_irq(pdev, 0);
    }
}

