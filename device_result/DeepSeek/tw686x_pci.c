/* MMIO/PIO Handlers generated during Behavioral Modeling */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    if (addr >= 0x1000) {
        return ~0ULL;
    }

    if (size == 4) {
        uint32_t reg_index = addr >> 2;
        if (reg_index >= ARRAY_SIZE(s->regs)) {
            return ~0ULL;
        }
        val = s->regs[reg_index];
        /* INT_STATUS clear-on-read */
        if (addr == INT_STATUS) {
            s->regs[reg_index] = 0;
            pcibase_update_irq(s);
        }
    } else {
        val = ~0ULL;
    }
    return val;
}

static void pcibase_mmio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;

    if (addr >= 0x1000) {
        return;
    }

    if (size == 4) {
        uint32_t reg_index = addr >> 2;
        if (reg_index >= ARRAY_SIZE(s->regs)) {
            return;
        }
        s->regs[reg_index] = val;
        /* No side effects required for probe; extended behavior can be added later */
    }
}

