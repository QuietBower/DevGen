/* Helper to generate non-zero random 64-bit values */
static uint64_t get_random_u64(void)
{
    uint64_t val;
    do {
        val = ((uint64_t)g_random_int() << 32) | g_random_int();
    } while (val == 0);
    return val;
}

/* MMIO/PIO Handlers generated during Behavioral Modeling */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    /* Handle reads to registers that the driver accesses */
    switch (addr) {
    case RNM_PF_EBG_HEALTH:
        val = 0; /* health status OK, no error bits set */
        break;
    case RNM_PF_RANDOM:
        val = get_random_u64();
        break;
    case RNM_PF_TRNG_DAT:
        val = get_random_u64();
        break;
    case RNM_PF_TRNG_RES:
        val = 0; /* no TRNG result pending */
        break;
    default:
        /* Return shadow register value for other offsets (may be zero) */
        if ((addr / 8) < ARRAY_SIZE(s->regs)) {
            val = s->regs[addr / 8];
        }
        break;
    }
    return val;
}

