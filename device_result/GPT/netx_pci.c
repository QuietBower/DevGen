/* MMIO/PIO Handlers generated during Behavioral Modeling */
static uint64_t pcibase_mmio_read(void *opaque, hwaddr addr, unsigned size)
{
    PCIBaseState *s = opaque;
    uint64_t val = 0;

    /* The driver uses ioread32, so support 32-bit accesses.
     * We also allow 1/2/8-byte accesses to avoid QEMU assertions. */

    switch (addr) {
    case DPM_HOST_INT_EN0:
        if (size == 4) {
            val = s->dpm_host_int_en0;
        }
        break;
    case DPM_HOST_INT_STAT0:
        if (size == 4) {
            val = s->dpm_host_int_stat0;
        }
        break;
    default:
        /* All other locations read as zero. */
        val = 0;
        break;
    }

    return val;
}

static void pcibase_mmio_write(void *opaque, hwaddr addr, uint64_t val, unsigned size)
{
    PCIBaseState *s = opaque;

    /* The driver uses iowrite32. We honor 32-bit writes and ignore others. */

    switch (addr) {
    case DPM_HOST_INT_EN0:
        if (size == 4) {
            /* Driver writes 0 here to disable all interrupts. */
            s->dpm_host_int_en0 = (uint32_t)val;
            pcibase_update_irq(s);
        }
        break;
    case DPM_HOST_INT_STAT0:
        if (size == 4) {
            /* Status register semantics are not defined by the driver.
             * Implement a write-1-to-clear behavior which is common and
             * does not contradict the driver's usage (it never writes here). */
            s->dpm_host_int_stat0 &= ~((uint32_t)val);
            pcibase_update_irq(s);
        }
        break;
    default:
        /* Ignore writes to undefined offsets. */
        break;
    }
}

