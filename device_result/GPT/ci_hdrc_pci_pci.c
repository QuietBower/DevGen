/*
 * QEMU PCI device model for ci_hdrc_pci.c host controller stub
 *
 * This emulates just enough PCI-level behavior for the Linux
 * ci_hdrc_pci driver to probe and bind. The actual USB core
 * registers and functionality are not modeled here because they
 * are not accessed directly in ci_hdrc_pci.c.
 */

