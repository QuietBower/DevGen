/*
 * QEMU PCI device model for intel_scu_pcidrv.c
 *
 * This model is intentionally minimal: the reference Linux driver
 * only enables the PCI device, exposes BAR0 and IRQ through
 * intel_scu_ipc_data, and then delegates to intel_scu_ipc_register().
 *
 * With the newly provided intel_scu_ipc_data and intel_scu_ipc_dev
 * definitions, we still see only that the driver needs:
 *   - A valid MMIO resource in struct resource mem (BAR0)
 *   - A valid IRQ number in data.irq
 * The driver does not access any specific registers or perform
 * MMIO/PIO/DMA/IRQ interactions on this PCI device directly.
 *
 * Therefore, the MMIO handlers remain no-op/read-as-zero, and no
 * interrupt or DMA behavior is modeled.
 */

